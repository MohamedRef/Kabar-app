//! The numbers in `README.md`, counted from the repository. `kabar-tools
//! readme` rewrites the block between the two markers; `--check` reports when
//! the block differs from what the files say (advisory in CI: the daily README
//! refresh commits it, so parallel PRs never race on it).
//!
//! Everything here is derived from committed files only (no clock, no git),
//! so the same tree always renders the same block.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use serde_json::Value;

use crate::paths::Root;

pub const BEGIN: &str = "<!-- kabar-stats:begin (generated by `just readme`, do not edit by hand) -->";
pub const END: &str = "<!-- kabar-stats:end -->";

pub fn run(root: &Root, check: bool) -> Result<()> {
    let path = root.path().join("README.md");
    let readme = fs::read_to_string(&path).with_context(|| path.display().to_string())?;
    let block = render(root.path())?;
    let updated = splice(&readme, &block)?;
    if updated == readme {
        println!("README.md stats are up to date");
        return Ok(());
    }
    if check {
        bail!(
            "README.md stats are out of date: run `just readme` (cargo run -p kabar-tools -- readme) and commit"
        );
    }
    fs::write(&path, updated)?;
    println!("README.md stats updated");
    Ok(())
}

/// Replaces everything between [`BEGIN`] and [`END`] with `block`.
fn splice(readme: &str, block: &str) -> Result<String> {
    let (Some(start), Some(end)) = (readme.find(BEGIN), readme.find(END)) else {
        bail!("README.md has no stats markers ({BEGIN} … {END})");
    };
    if end < start {
        bail!("README.md stats markers are out of order");
    }
    Ok(format!("{}{BEGIN}\n{block}{}", &readme[..start], &readme[end..]))
}

/// One level of a curriculum, with what has been written for it.
#[derive(Default)]
struct LevelRow {
    code: String,
    place: String,
    cefr: String,
    units: usize,
    planned: usize,
    written: usize,
    exercises: usize,
    new_words: usize,
    /// Distinct words taught up to the end of this level, and the plan.
    /// Javanese leaves out words spelled and meaning like an Indonesian new
    /// word (#289) or marked `same_as_id` (a near-twin like bedha, a chat
    /// abbreviation like udh); a false friend (mau "a moment ago") still counts.
    known: usize,
    target: Option<u64>,
    minutes: u64,
    test_items: usize,
}

fn render(root: &Path) -> Result<String> {
    let lessons = lesson_files(root)?;
    let tests = test_items(root)?;
    let indonesian: BTreeSet<String> = lessons
        .iter()
        .filter(|(id, _)| id.starts_with("bipa"))
        .flat_map(|(_, l)| l.1.iter().cloned())
        .collect();
    let mut out = String::new();

    for (file, name) in [("indonesian.yaml", "Indonesian (BIPA 1–7)"), ("javanese.yaml", "Javanese (J1–J6)")]
    {
        let twins = if file == "javanese.yaml" { Some(&indonesian) } else { None };
        let rows = levels(root, file, &lessons, &tests, twins)?;
        out += &format!("\n**{name}**\n\n");
        out += "| Level | Journey | CEFR (approx.) | Units | Lessons written | Exercises | New words | Known / target | Lesson time | Level test items |\n";
        out += "|---|---|---|--:|--:|--:|--:|--:|--:|--:|\n";
        let mut total = LevelRow::default();
        for r in &rows {
            out += &row(r, &r.code);
            total.units += r.units;
            total.planned += r.planned;
            total.written += r.written;
            total.exercises += r.exercises;
            total.new_words += r.new_words;
            (total.known, total.target) = (r.known, r.target);
            total.minutes += r.minutes;
            total.test_items += r.test_items;
        }
        out += &row(&total, "**Total**");
    }

    let placement = tests.get("placement").copied().unwrap_or(0);
    let grammar = |lang| count_files(&root.join("content/grammar").join(lang), "yaml");
    let (gloss_id, gloss_id_open) = glosses(root, "id")?;
    let (gloss_jv, gloss_jv_open) = glosses(root, "jv")?;
    let golden_dir = root.join("content/golden");
    let golden_sets = count_files(&golden_dir, "yaml")?;
    let golden_items = sum_yaml(&golden_dir, |v| len(&v["items"]))?;
    let aksara = len(&yaml(&root.join("content/aksara/glyphs.yaml"))?["glyphs"]);
    let prompts = fs::read_dir(root.join("prompts"))?
        .filter_map(|e| e.ok())
        .filter(|e| e.file_name().to_string_lossy().contains('@'))
        .count();
    let packs = count_files(&root.join("content/packs/id"), "json")?
        + count_files(&root.join("content/packs/jv"), "json")?;

    out += "\n**Reference content and stories**\n\n";
    out += "| What | Count | Notes |\n|---|--:|---|\n";
    let lines: Vec<(&str, String, String)> = vec![
        ("Placement test items", n(placement), "one test, easiest section first".into()),
        (
            "Grammar points",
            n(grammar("id")? + grammar("jv")?),
            format!("{} Indonesian, {} Javanese", n(grammar("id")?), n(grammar("jv")?)),
        ),
        ("Indonesian glosses", n(gloss_id), awaiting(gloss_id_open)),
        ("Javanese glosses", n(gloss_jv), awaiting(gloss_jv_open)),
        (
            "Arabic Bridge entries",
            n(lines_in(&root.join("content/bridge/id.jsonl"))?),
            "Arabic loans, shifts and false friends".into(),
        ),
        (
            "Javanese speech-level rows",
            n(lines_in(&root.join("content/javanese/speech-levels.jsonl"))?),
            "ngoko / krama / krama inggil".into(),
        ),
        (
            "Pronunciation lexicon",
            n(lines_in(&root.join("content/pron/id.tsv"))?),
            format!("plus {} hand overrides", n(lines_in(&root.join("content/pron/overrides.tsv"))?)),
        ),
        (
            "Sinetron episodes",
            n(count_files(&root.join("content/stories/sinetron"), "yaml")?),
            "each unlocks after its unit".into(),
        ),
        (
            "Kabar Radio episodes",
            n(count_files(&root.join("content/radio/id"), "yaml")?
                + count_files(&root.join("content/radio/jv"), "yaml")?),
            "prebuilt, downloadable for offline".into(),
        ),
        ("Conversation personas", n(count_files(&root.join("content/personas"), "yaml")?), String::new()),
        (
            "Kabar Pagi stories",
            n(lines_in(&root.join("content/pagi/stories.jsonl"))?),
            "morning stories".into(),
        ),
        (
            "Games",
            n(count_files(&root.join("content/games"), "toml")?),
            "Pasar!, Unggah-Ungguh, Minimal Pairs".into(),
        ),
        ("Aksara Jawa glyphs", n(aksara), "stroke order is a draft (pen work paused)".into()),
        ("Golden-set items", n(golden_items), format!("{golden_sets} golden sets for the AI tasks")),
        ("Versioned AI prompts", n(prompts), "`prompts/`".into()),
        ("Offline pack manifests", n(packs), "one per unit".into()),
    ];
    for (what, count, note) in lines {
        out += &format!("| {what} | {count} | {note} |\n");
    }
    out += "\n";
    Ok(out)
}

fn row(r: &LevelRow, label: &str) -> String {
    let written =
        if r.written == r.planned { n(r.written) } else { format!("{} / {}", n(r.written), n(r.planned)) };
    let known = match r.target {
        Some(t) => format!("{} / {}", n(r.known), n(t as usize)),
        None => n(r.known),
    };
    format!(
        "| {label} | {} | {} | {} | {written} | {} | {} | {known} | {} | {} |\n",
        r.place,
        if r.cefr.is_empty() { "—" } else { &r.cefr },
        r.units,
        n(r.exercises),
        n(r.new_words),
        hours(r.minutes),
        n(r.test_items)
    )
}

fn awaiting(open: usize) -> String {
    if open == 0 { "all approved".into() } else { format!("{} awaiting your review", n(open)) }
}

/// Lesson id → (exercises, new words lower-cased, the false friends among
/// them, the ones marked `same_as_id`), for every file in `content/lessons/`.
fn lesson_files(root: &Path) -> Result<BTreeMap<String, Lesson>> {
    let mut out = BTreeMap::new();
    for f in yaml_files(&root.join("content/lessons"))? {
        let v = yaml(&f)?;
        let id = v["id"].as_str().with_context(|| format!("{}: no id", f.display()))?.to_string();
        let all = || v["new_words"].as_array().into_iter().flatten();
        let words = all().map(|w| str_of(&w["word"]).to_lowercase()).collect();
        let marked = |key: &str| {
            all()
                .filter(|w| !w[key].is_null() && w[key] != false)
                .map(|w| str_of(&w["word"]).to_lowercase())
                .collect()
        };
        out.insert(id, (len(&v["exercises"]), words, marked("false_friend"), marked("same_as_id")));
    }
    Ok(out)
}

/// Test id → number of items, for every file in `content/tests/`.
fn test_items(root: &Path) -> Result<BTreeMap<String, usize>> {
    let mut out = BTreeMap::new();
    for f in yaml_files(&root.join("content/tests"))? {
        let v = yaml(&f)?;
        let id = v["id"].as_str().with_context(|| format!("{}: no id", f.display()))?.to_string();
        let items = v["sections"].as_array().map_or(0, |s| s.iter().map(|s| len(&s["items"])).sum());
        out.insert(id, items);
    }
    Ok(out)
}

type Lesson = (usize, Vec<String>, BTreeSet<String>, BTreeSet<String>);

/// `twins`: words that only count as known when they are false friends;
/// with `twins`, words marked `same_as_id` never count.
fn levels(
    root: &Path,
    file: &str,
    lessons: &BTreeMap<String, Lesson>,
    tests: &BTreeMap<String, usize>,
    twins: Option<&BTreeSet<String>>,
) -> Result<Vec<LevelRow>> {
    let c = yaml(&root.join("curriculum").join(file))?;
    let mut rows = Vec::new();
    let mut known = BTreeSet::new();
    for level in c["levels"].as_array().into_iter().flatten() {
        let mut r = LevelRow {
            code: str_of(&level["code"]),
            place: str_of(&level["journey"]["place"]),
            cefr: str_of(&level["cefr"]["approx"]),
            target: level["vocab_target"].as_u64(),
            ..LevelRow::default()
        };
        for unit in level["units"].as_array().into_iter().flatten() {
            r.units += 1;
            for lesson in unit["lessons"].as_array().into_iter().flatten() {
                r.planned += 1;
                r.minutes += lesson["minutes"].as_u64().unwrap_or(0);
                if let Some((ex, words, false_friends, same)) = lessons.get(&str_of(&lesson["id"])) {
                    r.written += 1;
                    r.exercises += ex;
                    r.new_words += words.len();
                    let counts = |w: &&String| {
                        twins.is_none_or(|t| {
                            (!t.contains(*w) || false_friends.contains(*w)) && !same.contains(*w)
                        })
                    };
                    known.extend(words.iter().filter(counts).cloned());
                }
            }
        }
        r.known = known.len();
        r.test_items = tests.get(&str_of(&level["level_test"]["id"])).copied().unwrap_or(0);
        rows.push(r);
    }
    Ok(rows)
}

/// (entries, entries not yet approved) over `content/glosses/<lang>/*.jsonl`.
fn glosses(root: &Path, lang: &str) -> Result<(usize, usize)> {
    let (mut all, mut open) = (0, 0);
    for f in files(&root.join("content/glosses").join(lang), "jsonl")? {
        for line in fs::read_to_string(&f)?.lines().filter(|l| !l.trim().is_empty()) {
            let v: Value = serde_json::from_str(line).with_context(|| f.display().to_string())?;
            all += 1;
            if v["status"].as_str() != Some("approved") {
                open += 1;
            }
        }
    }
    Ok((all, open))
}

fn yaml(path: &Path) -> Result<Value> {
    let text = fs::read_to_string(path).with_context(|| path.display().to_string())?;
    serde_yaml_ng::from_str(&text).with_context(|| path.display().to_string())
}

fn sum_yaml(dir: &Path, f: impl Fn(&Value) -> usize) -> Result<usize> {
    files(dir, "yaml")?.iter().map(|p| yaml(p).map(|v| f(&v))).sum()
}

fn len(v: &Value) -> usize {
    v.as_array().map_or(0, Vec::len)
}

fn str_of(v: &Value) -> String {
    v.as_str().unwrap_or_default().to_string()
}

fn lines_in(path: &Path) -> Result<usize> {
    let text = fs::read_to_string(path).with_context(|| path.display().to_string())?;
    Ok(text.lines().filter(|l| !l.trim().is_empty() && !l.starts_with('#')).count())
}

/// Files with extension `ext` directly in `dir` (none when `dir` is missing), sorted.
fn files(dir: &Path, ext: &str) -> Result<Vec<PathBuf>> {
    if !dir.is_dir() {
        return Ok(Vec::new());
    }
    let mut out: Vec<PathBuf> = fs::read_dir(dir)?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|e| e == ext))
        .collect();
    out.sort();
    Ok(out)
}

fn count_files(dir: &Path, ext: &str) -> Result<usize> {
    Ok(files(dir, ext)?.len())
}

/// Every `.yaml` under `dir`, recursively, sorted.
fn yaml_files(dir: &Path) -> Result<Vec<PathBuf>> {
    let mut out = files(dir, "yaml")?;
    for e in fs::read_dir(dir)? {
        let p = e?.path();
        if p.is_dir() {
            out.extend(yaml_files(&p)?);
        }
    }
    out.sort();
    Ok(out)
}

/// 12345 → "12,345".
fn n(v: usize) -> String {
    let s = v.to_string();
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if i > 0 && (s.len() - i).is_multiple_of(3) {
            out.push(',');
        }
        out.push(c);
    }
    out
}

/// 545 → "~9 h", 50 → "50 min".
fn hours(minutes: u64) -> String {
    if minutes < 90 { format!("{minutes} min") } else { format!("~{} h", (minutes + 30) / 60) }
}

