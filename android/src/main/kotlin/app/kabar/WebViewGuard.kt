import android.app.Activity
import android.app.ActivityManager
import android.app.ApplicationExitInfo
import android.content.Context
import android.content.Intent
import android.graphics.Bitmap
import android.os.Build
import android.os.Handler
import android.os.Looper
import android.os.Process
import android.util.Log
import android.view.View
import android.view.ViewGroup
import android.webkit.RenderProcessGoneDetail
import android.webkit.WebResourceError
import android.webkit.WebResourceRequest
import android.webkit.WebResourceResponse
import android.webkit.WebView
import android.webkit.WebViewClient
import java.time.Instant

/**
 * Keeps a lost WebView renderer from crashing Kabar, and says afterwards why
 * earlier runs ended.
 *
 * Kabar's whole screen is one WebView in its own renderer process. While
 * Kabar sits in the background, Android (One UI especially) reclaims that
 * renderer when memory runs short. A WebViewClient that doesn't handle
 * [WebViewClient.onRenderProcessGone] makes Android kill the app with it,
 * counted as a crash: Device Care then says "Kabar is crashing frequently".
 * wry's RustWebViewClient (generated by dx) doesn't handle it, so [install]
 * wraps it in [Guard], which forwards everything wry handles and takes the
 * renderer's loss itself: in the background Kabar simply ends (the next
 * open starts fresh, like after any reclaim); in front it starts again.
 * Learning data is already saved: every answer is written as it happens.
 *
 * [install] also returns how recent runs ended (ApplicationExitInfo,
 * Android 11+) for Settings › Storage › diagnostics, so a crash on the
 * phone leaves its reason somewhere it can be copied from.
 */
object WebViewGuard {
    private const val TAG = "KabarWebView"
    private const val PREFS = "kabar_exits"
    private const val SEEN = "seen"
    private const val GONE = "renderer_gone"
    /** How long [install] keeps looking for wry's WebView (it may come after the first render). */
    private const val TRIES = 40
    private const val RETRY_MS = 250L

    /**
     * Wraps the WebView's client once it exists, and returns how the runs
     * since the last call ended, one per line (empty when nothing new).
     */
    @JvmStatic
    fun install(activity: Activity): String {
        activity.runOnUiThread { attach(activity, 0) }
        return exits(activity.applicationContext)
    }

    private fun attach(activity: Activity, tries: Int) {
        if (activity.isFinishing || activity.isDestroyed) return
        val web = find(activity.window.decorView)
        val inner = web?.webViewClient
        if (web == null || inner == null || inner.javaClass == WebViewClient::class.java) {
            if (tries < TRIES) {
                Handler(Looper.getMainLooper()).postDelayed({ attach(activity, tries + 1) }, RETRY_MS)
            } else {
                Log.w(TAG, "No WebView to guard")
            }
            return
        }
        if (inner !is Guard) web.webViewClient = Guard(activity, inner)
    }

    private fun find(view: View): WebView? {
        if (view is WebView) return view
        if (view is ViewGroup) {
            for (i in 0 until view.childCount) find(view.getChildAt(i))?.let { return it }
        }
        return null
    }

    /** The renderer is gone: leaves a note for the next start, then ends or restarts Kabar. */
    internal fun rendererGone(activity: Activity, crashed: Boolean) {
        val front = UpdateInstaller.inForeground()
        val why = if (crashed) "crashed" else "was stopped by Android"
        val where = if (front) "in front" else "in the background"
        Log.w(TAG, "WebView renderer $why ($where)")
        activity.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit()
            .putString(GONE, "${Instant.now()} screen renderer $why $where; Kabar ${if (front) "restarted" else "closed"} instead of crashing")
            .commit()
        if (front) {
            activity.packageManager.getLaunchIntentForPackage(activity.packageName)
                ?.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TASK)
                ?.let {
                    try {
                        activity.startActivity(it)
                    } catch (e: Exception) {
                        Log.w(TAG, "Restart failed", e)
                    }
                }
        }
        // The Rust side and its WebView can't be rebuilt in this process.
        Process.killProcess(Process.myPid())
    }

    /** New exit records since the last call, oldest first. */
    private fun exits(context: Context): String {
        val prefs = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
        val lines = mutableListOf<String>()
        prefs.getString(GONE, null)?.let { lines.add(it) }
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            val seen = prefs.getLong(SEEN, 0L)
            val am = context.getSystemService(ActivityManager::class.java)
            val records = try {
                am?.getHistoricalProcessExitReasons(context.packageName, 0, 10).orEmpty()
            } catch (e: Exception) {
                emptyList()
            }
            val fresh = records.filter { it.timestamp > seen }.sortedBy { it.timestamp }
            for (r in fresh) {
                val about = r.description?.takeIf { it.isNotBlank() }?.let { ": $it" } ?: ""
                lines.add(
                    "${Instant.ofEpochMilli(r.timestamp)} last run ended: ${reason(r.reason)}" +
                        " (${importance(r.importance)})$about",
                )
            }
            fresh.lastOrNull()?.let { prefs.edit().putLong(SEEN, it.timestamp).apply() }
        }
        prefs.edit().remove(GONE).apply()
        return lines.joinToString("\n")
    }

    private fun reason(code: Int): String = when (code) {
        ApplicationExitInfo.REASON_EXIT_SELF -> "exited"
        ApplicationExitInfo.REASON_SIGNALED -> "signalled"
        ApplicationExitInfo.REASON_LOW_MEMORY -> "low memory"
        ApplicationExitInfo.REASON_CRASH -> "CRASH (Java)"
        ApplicationExitInfo.REASON_CRASH_NATIVE -> "CRASH (native)"
        ApplicationExitInfo.REASON_ANR -> "ANR (not responding)"
        ApplicationExitInfo.REASON_INITIALIZATION_FAILURE -> "failed to start"
        ApplicationExitInfo.REASON_PERMISSION_CHANGE -> "permission changed"
        ApplicationExitInfo.REASON_EXCESSIVE_RESOURCE_USAGE -> "too much resource use"
        ApplicationExitInfo.REASON_USER_REQUESTED -> "stopped by the user"
        ApplicationExitInfo.REASON_USER_STOPPED -> "user stopped"
        ApplicationExitInfo.REASON_DEPENDENCY_DIED -> "dependency died"
        ApplicationExitInfo.REASON_OTHER -> "other (system)"
        else -> "reason $code"
    }

    private fun importance(code: Int): String =
        if (code <= ActivityManager.RunningAppProcessInfo.IMPORTANCE_FOREGROUND) "in front" else "in the background"
}

/**
 * wry's client with [onRenderProcessGone] handled. Every callback wry
 * overrides is forwarded unchanged; the rest keep WebViewClient's defaults,
 * which is what wry's client would do with them too.
 */
private class Guard(private val activity: Activity, private val inner: WebViewClient) : WebViewClient() {
    override fun shouldInterceptRequest(view: WebView, request: WebResourceRequest): WebResourceResponse? =
        inner.shouldInterceptRequest(view, request)

    override fun shouldOverrideUrlLoading(view: WebView, request: WebResourceRequest): Boolean =
        inner.shouldOverrideUrlLoading(view, request)

    override fun onPageStarted(view: WebView, url: String, favicon: Bitmap?) =
        inner.onPageStarted(view, url, favicon)

    override fun onPageFinished(view: WebView, url: String) = inner.onPageFinished(view, url)

    override fun onReceivedError(view: WebView, request: WebResourceRequest, error: WebResourceError) =
        inner.onReceivedError(view, request, error)

    override fun onRenderProcessGone(view: WebView, detail: RenderProcessGoneDetail): Boolean {
        // Android must not touch this WebView again: take it out first.
        (view.parent as? ViewGroup)?.removeView(view)
        WebViewGuard.rendererGone(activity, detail.didCrash())
        return true
    }
}
