#!/usr/bin/env python3
"""Turns Firebase's google-services.json into the Android string resources
Firebase reads at start-up, for Kak Nur's pushed reminders (issue #187).

The google-services Gradle plugin normally does this, but dx generates the
Gradle project, so Kabar writes the same resources into android/ (a library
module dx copies in) and Firebase's own init provider picks them up.

The JSON comes from, in order: the first argument (a path), the
KABAR_GOOGLE_SERVICES_JSON environment variable (the file's contents: CI's
repo secret), or ~/.kabar/google-services.json (the Mac). With none of them
the resources are removed and the APK has no Firebase: reminders stay local.

Both outputs are git-ignored: the settings never go in the repo.
"""

import json
import os
import sys
from pathlib import Path
from xml.sax.saxutils import escape

PACKAGE = "app.kabar"
ROOT = Path(__file__).resolve().parent.parent
VALUES = ROOT / "android/src/main/res/values/kabar_firebase.xml"
KEEP = ROOT / "android/src/main/res/raw/kabar_firebase_keep.xml"
NAMES = ("google_app_id", "gcm_defaultSenderId", "google_api_key", "project_id")


def source():
    if len(sys.argv) > 1:
        return Path(sys.argv[1]).read_text(), sys.argv[1]
    env = os.environ.get("KABAR_GOOGLE_SERVICES_JSON", "").strip()
    if env:
        return env, "KABAR_GOOGLE_SERVICES_JSON"
    home = Path.home() / ".kabar/google-services.json"
    if home.is_file():
        return home.read_text(), str(home)
    return None, None


def strings(config):
    """The four values Firebase needs, for the app.kabar client."""
    project = config["project_info"]
    for client in config.get("client", []):
        info = client.get("client_info", {})
        if info.get("android_client_info", {}).get("package_name") != PACKAGE:
            continue
        keys = [k["current_key"] for k in client.get("api_key", []) if k.get("current_key")]
        if not keys:
            raise ValueError("the app.kabar client has no api_key")
        return {
            "google_app_id": info["mobilesdk_app_id"],
            "gcm_defaultSenderId": project["project_number"],
            "google_api_key": keys[0],
            "project_id": project["project_id"],
        }
    raise ValueError(f"no Android client for {PACKAGE}: add the app in the Firebase console")


def main():
    text, origin = source()
    if text is None:
        for f in (VALUES, KEEP):
            f.unlink(missing_ok=True)
        print("No google-services.json: this build has no Firebase (reminders stay local).")
        return 0
    try:
        values = strings(json.loads(text))
    except (ValueError, KeyError, TypeError) as e:
        print(f"{origin} is not a usable google-services.json: {e}", file=sys.stderr)
        return 1
    VALUES.parent.mkdir(parents=True, exist_ok=True)
    KEEP.parent.mkdir(parents=True, exist_ok=True)
    rows = "\n".join(
        f'    <string name="{n}" translatable="false">{escape(str(values[n]))}</string>' for n in NAMES
    )
    VALUES.write_text(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
        "<!-- Generated by scripts/android-firebase.py; git-ignored. -->\n"
        f"<resources>\n{rows}\n</resources>\n"
    )
    # Firebase looks these up by name, which resource shrinking can't see.
    keep = ",".join(f"@string/{n}" for n in NAMES)
    KEEP.write_text(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
        '<resources xmlns:tools="http://schemas.android.com/tools"\n'
        f'    tools:keep="{keep}" />\n'
    )
    print(f"Firebase settings for {PACKAGE} (project {values['project_id']}) from {origin}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
